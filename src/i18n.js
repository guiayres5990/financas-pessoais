// Lê o idioma salvo em fp_lang. "es" (removido) vira inglês; sem escolha salva, navegador em
// espanhol também cai em inglês; qualquer outro caso fica no padrão, português.
export function normalizarIdioma(valor) {
  const v = String(valor || "").toLowerCase();
  if (v === "pt" || v.startsWith("pt-")) return "pt";
  if (v === "en" || v.startsWith("en-")) return "en";
  if (v === "es" || v.startsWith("es-")) return "en";
  return null;
}
export function idiomaInicial() {
  let salvo = null;
  try { salvo = localStorage.getItem("fp_lang"); } catch { /* sem localStorage */ }
  if (salvo) return normalizarIdioma(salvo) || "pt";
  const nav = typeof navigator !== "undefined" ? String(navigator.language || "") : "";
  return nav.toLowerCase().startsWith("es") ? "en" : "pt";
}

